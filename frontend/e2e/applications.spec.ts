import { expect, test } from '@playwright/test';

test('administrator maintains and exports application inventory', async ({ page }) => {
  const password = process.env.E2E_PASSWORD;
  if (!password) throw new Error('Set E2E_PASSWORD to the configured demo bootstrap password');
  const errors: string[] = [];
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('pageerror', error => errors.push(error.message));
  const portfolio = `Application portfolio ${Date.now()}`;
  const name = `Application journey ${Date.now()}`;
  await page.goto('/');
  await page.getByLabel('Email address').fill('admin@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Portfolios', exact: true }).click();
  await page.getByRole('link', { name: 'Create portfolio' }).click();
  await page.getByLabel('Name', { exact: true }).fill(portfolio);
  await page.getByRole('button', { name: 'Save portfolio' }).click();
  await expect(page.getByRole('heading', { name: portfolio })).toBeVisible();
  await page.getByRole('link', { name: 'Applications', exact: true }).click();
  await page.getByRole('link', { name: 'Create application' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Portfolio', { exact: true }).selectOption({ label: portfolio });
  await page.getByLabel('Business owner').fill('Journey owner');
  await page.getByLabel('Quality score').fill('85');
  await page.getByRole('button', { name: 'Save application' }).click();
  await expect(page.getByRole('heading', { name })).toBeVisible();
  await expect(page.getByText('Journey owner')).toBeVisible();
  await page.getByRole('link', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Quality score').fill('91');
  await page.getByRole('button', { name: 'Save application' }).click();
  await expect(page.getByText('91', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: '← Applications' }).click();
  await page.getByLabel('Search').fill(name);
  await expect(page.getByRole('link', { name })).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await downloadPromise).suggestedFilename()).toBe('applications.csv');
  await page.getByRole('link', { name }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete application' }).click();
  await expect(page.getByRole('heading', { name: 'Application repository' })).toBeVisible();
  await page.getByRole('link', { name: 'Portfolios', exact: true }).click();
  await page.getByLabel('Search').fill(portfolio);
  await page.getByRole('link', { name: portfolio }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete portfolio' }).click();
  expect(errors).toEqual([]);
});
